"""GTA V native DB: search, exact lookup, and a current natives.h for the ScriptHookV SDK.

Data: knowledge/natives.json.gz (alloc8or gta5-nativedb-data, 6,701 natives). Each native:
name, ns, hash (64-bit invoker hash), jhash (old joaat hash), returns, params, build, old_names.
"""
from __future__ import annotations

import gzip
import json
import re
from functools import lru_cache
from pathlib import Path

from .util import KNOWLEDGE_DIR, ForgeError

DB_FILE = KNOWLEDGE_DIR / "natives.json.gz"
CPP_RESERVED = {"default", "this", "new", "delete", "char", "int", "float", "bool", "class", "struct", "template",
                "operator", "register", "auto", "union", "type", "unsigned", "signed", "short", "long", "double",
                "return", "switch", "case", "public", "private", "protected", "friend", "virtual", "near", "far"}


@lru_cache(maxsize=1)
def _doc() -> dict:
    if not DB_FILE.is_file():
        raise ForgeError(f"native DB missing: {DB_FILE}", "reinstall the forge (git checkout)")
    with gzip.open(DB_FILE, "rt", encoding="utf-8") as f:
        return json.load(f)


def _db() -> list[dict]:
    return _doc()["natives"]


@lru_cache(maxsize=1)
def by_name() -> dict[str, dict]:
    out: dict[str, dict] = {}
    for n in _db():
        out[n["name"]] = n
    for n in _db():
        for old in n.get("old_names") or []:
            out.setdefault(old, n)
    return out


@lru_cache(maxsize=1)
def by_hash() -> dict[str, dict]:
    out = {}
    for n in _db():
        out[n["hash"]] = n
        if n.get("jhash"):
            out.setdefault(n["jhash"], n)
    return out


def norm_hash(text: str) -> str:
    t = text.lower().strip()
    t = t[2:] if t.startswith("0x") else t
    return t.lstrip("0") or "0"


def lookup(name_or_hash: str) -> dict | None:
    """Exact native by current name, old name, or hash (0x... 64-bit or old joaat)."""
    q = name_or_hash.strip()
    if q.upper() in by_name():
        return by_name()[q.upper()]
    if re.fullmatch(r"(0x)?[0-9a-fA-F]{6,16}", q):
        want = norm_hash(q)
        for h, n in by_hash().items():
            if h.lstrip("0") == want:
                return n
    return None


def signature(n: dict) -> str:
    params = ", ".join(f"{p['type']} {p['name']}" for p in n["params"])
    return f"{n['returns']} {n['ns']}::{n['name']}({params})"


def search(query: str, limit: int = 25, ns: str | None = None) -> dict:
    q = query.strip()
    if not q:
        raise ForgeError("empty query", "gtaforge natives <name|part|0xhash>")
    exact = lookup(q)
    ql = q.lower()
    hits = []
    for n in _db():
        if ns and n["ns"].lower() != ns.lower():
            continue
        if ql in n["name"].lower() or ql == n["hash"] or ql.removeprefix("0x") == n["hash"] or ql == n["ns"].lower():
            hits.append(n)
    if exact and exact not in hits:
        hits.insert(0, exact)
    hits.sort(key=lambda n: (n is not exact, n["name"].lower() != ql, len(n["name"])))
    renamed = exact and q.upper() != exact["name"] and q.upper() in (exact.get("old_names") or [])
    return {"query": query, "count": len(hits), "total": len(_db()),
            "exact": ({"signature": signature(exact), **exact} if exact else None),
            "renamed_to": exact["name"] if renamed else None,
            "natives": [{"signature": signature(n), **n} for n in hits[:limit]],
            "source": _doc()["source"]}


def _cpp_type(t: str) -> str:
    t = t.strip()
    return {"void": "void"}.get(t, t)


def _cpp_name(name: str, used: set) -> str:
    n = re.sub(r"\W", "_", name or "p") or "p"
    if n in CPP_RESERVED or n[0].isdigit():
        n = n + "_"
    while n in used:
        n += "_"
    used.add(n)
    return n


def header(out: Path | None = None) -> dict:
    """Write a natives.h for the ScriptHookV SDK from the current DB (replaces the 2016 SDK header).

    Same shape as the SDK's own file: namespace NS { static RET NAME(args) { return invoke<RET>(hash, args); } }
    """
    lines = ["// natives.h - generated by GTA Forge from " + _doc()["source"],
             "// Replaces the ScriptHookV SDK's natives.h (2016) and nativeCaller.h (which stops at 25 arguments;",
             "// natives take up to 32). Needs the SDK's main.h (nativeInit / nativePush64 / nativeCall) and types.h.",
             "#pragma once", "#include \"main.h\"", "#include \"types.h\"", "#include <cstring>", "#include <type_traits>", "",
             "namespace gtaforge_detail {",
             "template <typename T> inline void push(T v) {",
             "\tstatic_assert(sizeof(T) <= sizeof(UINT64), \"native argument wider than 64 bits\");",
             "\tUINT64 v64 = 0; std::memcpy(&v64, &v, sizeof(T)); nativePush64(v64);",
             "}",
             "template <typename R, typename... A> inline R invoke(UINT64 hash, A... args) {",
             "\tnativeInit(hash); (push(args), ...);",
             "\tif constexpr (std::is_void_v<R>) { nativeCall(); } else { return *reinterpret_cast<R*>(nativeCall()); }",
             "}",
             "}  // namespace gtaforge_detail", ""]
    by_ns: dict[str, list[dict]] = {}
    for n in _db():
        by_ns.setdefault(n["ns"], []).append(n)
    count = 0
    for ns in sorted(by_ns):
        lines.append(f"namespace {ns}\n{{")
        for n in sorted(by_ns[ns], key=lambda x: x["name"]):
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", n["name"]):
                continue
            used: set = set()
            params = [(_cpp_type(p["type"]), _cpp_name(p["name"], used)) for p in n["params"]]
            ret = _cpp_type(n["returns"] or "void")
            sig = ", ".join(f"{t} {nm}" for t, nm in params)
            call = ", ".join([f"0x{n['hash'].upper()}"] + [nm for _t, nm in params])
            body = (f"gtaforge_detail::invoke<void>({call});" if ret == "void"
                    else f"return gtaforge_detail::invoke<{ret}>({call});")
            # inline, not static: no C4505 "unreferenced function" warning per unused native
            lines.append(f"\tinline {ret} {n['name']}({sig}) {{ {body} }} // 0x{n['hash'].upper()} b{n.get('build') or '?'}")
            count += 1
        lines.append("}\n")
    text = "\n".join(lines) + "\n"
    if out:
        out = Path(out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8", newline="\n")
    return {"natives": count, "namespaces": len(by_ns), "out": str(out) if out else None, "bytes": len(text.encode())}
